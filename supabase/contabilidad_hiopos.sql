alter table cuentas_contables add column if not exists referencia text;
alter table cuentas_contables add column if not exists cuenta_contable text;
alter table cuentas_contables add column if not exists cuenta_devolucion text;

update cuentas_contables set grupo_cuenta = 'MATERIAL DE EMPAQUE' where id = 574 and grupo_cuenta like '=%';

alter table cuentas_contables enable row level security;
drop policy if exists cc_leer on cuentas_contables;
create policy cc_leer on cuentas_contables for select to authenticated using (mi_rol() in ('admin', 'pagos'));
drop policy if exists cc_escribir on cuentas_contables;
create policy cc_escribir on cuentas_contables for all to authenticated using (mi_rol() = 'admin') with check (mi_rol() = 'admin');
revoke all on cuentas_contables from anon;
grant select, insert, update on cuentas_contables to authenticated;

create table if not exists contable_regla_familia (
  familia_norm      text primary key,          -- familia de Hiopos normalizada (FRUVER, ABARROTES...)
  familia_hiopos    text not null,
  familia           text,                      -- como la nombra contabilidad (Fruver)
  subfamilia        text,
  grupo_cuenta      text not null,
  referencia        text,
  cuenta_contable   text not null,
  cuenta_devolucion text,
  activo            boolean not null default true,
  confirmado_por    text,
  confirmado_en     timestamptz not null default now()
);
alter table contable_regla_familia enable row level security;
drop policy if exists crf_leer on contable_regla_familia;
create policy crf_leer on contable_regla_familia for select to authenticated using (mi_rol() in ('admin', 'pagos'));
drop policy if exists crf_escribir on contable_regla_familia;
create policy crf_escribir on contable_regla_familia for all to authenticated using (mi_rol() in ('admin', 'pagos')) with check (mi_rol() in ('admin', 'pagos'));
revoke all on contable_regla_familia from anon;
grant select, insert, update on contable_regla_familia to authenticated;

